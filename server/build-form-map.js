/* ============================================================
   Regenerates form-map.js from the page's own content model, so
   the questionnaire and the email/Excel output can never drift.

   Run it after editing questionnaire.js:
       node build-form-map.js
   ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const SRC = path.join(__dirname, '..', 'questionnaire', 'questionnaire.js');
const OUT = path.join(__dirname, 'form-map.js');

/* Everything before the CONFIGURATION banner is pure data. */
const src = fs.readFileSync(SRC, 'utf8');
const cut = src.indexOf('   CONFIGURATION');
if (cut < 0) throw new Error('CONFIGURATION marker not found in questionnaire.js');
const dataOnly = src.slice(0, src.lastIndexOf('/* =', cut));

const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(dataOnly + '\nthis.FORM = FORM; this.YN = YN; this.YNP = YNP;', sandbox);
const { FORM, YN, YNP } = sandbox;

/* Option labels, keyed by question id, so the server can print
   "Local market" rather than "local". */
const OPTIONS = { __yn: Object.fromEntries(YN.map(o => [o.v, {ar:o.ar, en:o.en}])) };
const addOpts = (id, list) => { OPTIONS[id] = Object.fromEntries(list.map(o => [o.v, {ar:o.ar, en:o.en}])); };
FORM.fx.fields.forEach(f => { if (f.opts) addOpts(f.id, f.opts); });
FORM.groups.forEach(g => g.q.forEach(q => {
  if (q.opts) addOpts(q.id, q.opts);
  else if (q.type === 'yn') addOpts(q.id, YN);
  else if (q.type === 'ynp') addOpts(q.id, YNP);
}));

const pick = (o, keys) => Object.fromEntries(keys.filter(k => o[k] != null).map(k => [k, o[k]]));

const map = {
  REF: FORM.ref,
  DOC: FORM.doc.fields.map(f => pick(f, ['id','ar','en'])),
  FX:  FORM.fx.fields.map(f => pick(f, ['id','ar','en'])),
  GROUPS: FORM.groups.map(g => ({
    id: g.id, ar: g.ar, en: g.en,
    q: g.q.map(q => pick(q, ['id','ar','en']))
  })),
  FIN:  FORM.fin.lines.map(l => pick(l, ['id','n','ar','en'])),
  MEMO: FORM.fin.memo.map(l => pick(l, ['id','n','ar','en'])),
  DOCS: FORM.docs.rows.map(d => pick(d, ['id','n','ar','en'])),
  OPTIONS
};

fs.writeFileSync(OUT,
  '/* GENERATED by build-form-map.js — do not edit by hand.\n' +
  '   Source of truth: ../questionnaire/questionnaire.js */\n' +
  "'use strict';\nmodule.exports = " + JSON.stringify(map, null, 2) + ';\n', 'utf8');

const n = map.GROUPS.reduce((s, g) => s + g.q.length, 0);
console.log(`form-map.js written — ${map.GROUPS.length} groups, ${n} questions, ${Object.keys(OPTIONS).length} option sets`);
